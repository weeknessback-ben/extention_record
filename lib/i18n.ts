const dictionaries = { en, id } as const;
type UiLanguage = keyof typeof dictionaries;

function detect(): UiLanguage {
  const lang = (globalThis.navigator?.language ?? 'en').toLowerCase();
  return lang.startsWith('id') || lang.startsWith('ms') ? 'id' : 'en';
}

let current: UiLanguage = detect();

export function setUiLanguage(pref: 'auto' | UiLanguage): void {
  current = pref === 'auto' ? detect() : pref;
  if (globalThis.document) document.documentElement.lang = current;
}

export function uiLanguage(): UiLanguage {
  return current;
}

export function t(key: I18nKey, vars: Record<string, string | number> = {}): string {
  const template: string = dictionaries[current][key] ?? en[key];
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}
